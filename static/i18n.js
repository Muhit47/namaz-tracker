// Generate Reverse Dictionary (English -> Bangla)
const DICT_EN_BN = {};
for (const [bn, en] of Object.entries(DICT_BN_EN)) {
    DICT_EN_BN[en] = bn;
}

let currentAppLanguage = localStorage.getItem("app_lang") || "bn";

function getAppLanguage() {
    return currentAppLanguage;
}

function t(text) {
    if (!text) return "";
    const clean = String(text).trim();
    if (currentAppLanguage === "en") {
        return DICT_BN_EN[clean] || clean;
    } else {
        return DICT_EN_BN[clean] || clean;
    }
}

function formatNumber(num) {
    if (num === null || num === undefined) return "";
    const str = String(num);
    const bnDigits = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];
    if (currentAppLanguage === "en") {
        return str.replace(/[০-৯]/g, d => bnDigits.indexOf(d));
    } else {
        return str.replace(/[0-9]/g, d => bnDigits[parseInt(d, 10)]);
    }
}

function setAppLanguage(lang) {
    if (lang !== "bn" && lang !== "en") lang = "bn";
    currentAppLanguage = lang;
    localStorage.setItem("app_lang", lang);
    document.documentElement.lang = lang;

    applyFullSitewideTranslation(lang);

    if (typeof window.onLanguageChanged === "function") {
        window.onLanguageChanged(lang);
    }
}

function toggleAppLanguage() {
    setAppLanguage(currentAppLanguage === "bn" ? "en" : "bn");
}

function applyFullSitewideTranslation(lang) {
    const isEn = lang === "en";

    // 1. Walk every text node in the document
    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        {
            acceptNode: function(node) {
                const parent = node.parentElement;
                if (!parent) return NodeFilter.FILTER_REJECT;
                const tag = parent.tagName.toUpperCase();
                if (tag === "SCRIPT" || tag === "STYLE" || tag === "NOSCRIPT") {
                    return NodeFilter.FILTER_REJECT;
                }
                // Preserve Arabic Quran/Hadith text
                if (parent.classList.contains("ayah-arabic") || parent.classList.contains("hadith-card-arabic") || 
                    parent.classList.contains("bismillah-arabic") || parent.classList.contains("arabic-name") ||
                    parent.classList.contains("arabic-text") || parent.classList.contains("hadith-widget-ar")) {
                    return NodeFilter.FILTER_REJECT;
                }
                return NodeFilter.FILTER_ACCEPT;
            }
        }
    );

    let node;
    while ((node = walker.nextNode())) {
        const text = node.nodeValue;
        if (!text || !text.trim()) continue;

        const trimmed = text.trim();

        // Exact match replacement
        if (isEn && DICT_BN_EN[trimmed]) {
            node.nodeValue = text.replace(trimmed, DICT_BN_EN[trimmed]);
        } else if (!isEn && DICT_EN_BN[trimmed]) {
            node.nodeValue = text.replace(trimmed, DICT_EN_BN[trimmed]);
        } else if (isEn) {
            // Partial / phrase replacements for longer matches
            for (const [bnStr, enStr] of Object.entries(DICT_BN_EN)) {
                if (bnStr.length > 2 && node.nodeValue.includes(bnStr)) {
                    node.nodeValue = node.nodeValue.split(bnStr).join(enStr);
                }
            }
        } else if (!isEn) {
            for (const [enStr, bnStr] of Object.entries(DICT_EN_BN)) {
                if (enStr.length > 2 && node.nodeValue.includes(enStr)) {
                    node.nodeValue = node.nodeValue.split(enStr).join(bnStr);
                }
            }
        }

        // Convert digits if language is English
        if (isEn && /[০-৯]/.test(node.nodeValue)) {
            node.nodeValue = node.nodeValue.replace(/[০-৯]/g, d => "০১২৩৪৫৬৭৮৯".indexOf(d));
        } else if (!isEn && /[0-9]/.test(node.nodeValue)) {
            const bnDigits = ["০", "১", "২", "৩", "৪", "৫", "৬", "৭", "৮", "৯"];
            node.nodeValue = node.nodeValue.replace(/[0-9]/g, d => bnDigits[parseInt(d, 10)]);
        }
    }

    // 2. Translate data-i18n elements
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (DICT_BN_EN[key]) {
            el.textContent = isEn ? DICT_BN_EN[key] : (DICT_EN_BN[DICT_BN_EN[key]] || key);
        }
    });

    // 3. Translate attributes (placeholder, title, aria-label)
    const elementsWithAttrs = document.querySelectorAll("[placeholder], [title], [aria-label]");
    elementsWithAttrs.forEach(el => {
        ["placeholder", "title", "aria-label"].forEach(attr => {
            const val = el.getAttribute(attr);
            if (!val || !val.trim()) return;
            const trimmed = val.trim();
            if (isEn && DICT_BN_EN[trimmed]) {
                el.setAttribute(attr, DICT_BN_EN[trimmed]);
            } else if (!isEn && DICT_EN_BN[trimmed]) {
                el.setAttribute(attr, DICT_EN_BN[trimmed]);
            } else if (isEn) {
                for (const [bnStr, enStr] of Object.entries(DICT_BN_EN)) {
                    if (bnStr.length > 2 && val.includes(bnStr)) {
                        el.setAttribute(attr, val.split(bnStr).join(enStr));
                    }
                }
            }
        });
    });

    // 4. Translate Select Options (Districts, Countries, etc.)
    document.querySelectorAll("select option").forEach(opt => {
        const text = opt.textContent.trim();
        if (isEn) {
            // Format 1: "Bangla (English)" -> extract English
            const mBnFirst = text.match(/\(([^)]+)\)$/);
            // Format 2: "English (Bangla)" -> extract English
            const mEnFirst = text.match(/^([A-Za-z0-9\s,'./\-]+)\s*\([^)]+\)$/);
            
            if (mEnFirst && mEnFirst[1]) {
                opt.textContent = mEnFirst[1].trim();
            } else if (mBnFirst && mBnFirst[1] && /^[A-Za-z0-9\s,'./\-]+$/.test(mBnFirst[1])) {
                opt.textContent = mBnFirst[1].trim();
            } else if (DICT_BN_EN[text]) {
                opt.textContent = DICT_BN_EN[text];
            }
        } else {
            const val = opt.value;
            const dataBn = opt.getAttribute("data-bn");
            if (dataBn && val) {
                opt.textContent = `${dataBn} (${val})`;
            } else if (DICT_EN_BN[text]) {
                opt.textContent = DICT_EN_BN[text];
            }
        }
    });

    // 5. Translate Optgroup Labels
    document.querySelectorAll("optgroup").forEach(og => {
        const label = og.getAttribute("label");
        if (!label) return;
        if (isEn) {
            if (DICT_BN_EN[label]) {
                og.setAttribute("label", DICT_BN_EN[label]);
            } else {
                const m = label.match(/\(([^)]+)\)$/);
                if (m && m[1]) {
                    og.setAttribute("label", m[1].trim());
                }
            }
        } else if (DICT_EN_BN[label]) {
            og.setAttribute("label", DICT_EN_BN[label]);
        }
    });

    // 6. Translate City Pill Buttons
    document.querySelectorAll(".city-pill-btn").forEach(btn => {
        const city = btn.getAttribute("data-city");
        const bn = btn.getAttribute("data-bn");
        if (city && bn) {
            btn.textContent = isEn ? city : bn;
        }
    });

    // 7. Update Language Switcher Pill UI
    const langBtn = document.getElementById("lang-switcher-btn");
    if (langBtn) {
        langBtn.innerHTML = `🌐 <span class="lang-text">${isEn ? "বাংলা" : "English"}</span>`;
        langBtn.title = isEn ? "বাংলায় পরিবর্তন করুন" : "Switch to English";
        langBtn.setAttribute("aria-label", isEn ? "বাংলায় পরিবর্তন করুন" : "Switch to English");
    }
}

